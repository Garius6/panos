const std = @import("std");
const wasi = std.os.wasi;

// WASI-половина AOT-рантайма, с которой линкуется сгенерированный `.wasm`-модуль
// (зеркалится `runtime_js.zig` для браузерной стороны — те же экспортируемые
// имена/сигнатуры, но другая хост-привязка). Ограничена ровно тем, что нужно
// `время.монотонно_мс`/`время.сейчас_мс` — рантайм таблицы объектов
// (`pw_string_ptr`/`arena`/`obj_offsets`/`obj_sizes`) здесь не задействован,
// так как строковые константы пока вообще не понижаются (`mir_emit.zig`).
// `pw_print_string`/`pw_println_string` намеренно не реализованы: изобретать
// раскладку таблицы объектов заранее, без реального вызывающего кода для
// проверки, не имеет смысла.
//
// `panos_runtime_abi_version` пока просто возвращает 0 — у ABI ещё нет
// реального потребителя (модули, испускаемые `panos build --target=wasm`,
// не импортируют из этого рантайма).

pub export fn panos_runtime_abi_version() u32 {
    return 0;
}

// WASI-шная `CLOCK_MONOTONIC` — наносекунды от произвольной, определяемой
// хостом точки отсчёта (обычно загрузка системы) — это НЕ та же эпоха, что у
// `время.монотонно_мс` байткод-VM (`vm.monotonic_epoch`, момент старта
// самого процесса). Числовое сравнение этих двух величин между байткод-VM и
// скомпилированным `.wasm`-модулем никогда не имело смысла — вызывающий код
// может сравнивать только РАЗНИЦЫ монотонных отметок в пределах одного
// процесса, но не абсолютное равенство между процессами.
pub export fn pw_monotonic_ms() f64 {
    var ts: wasi.timestamp_t = 0;
    _ = wasi.clock_time_get(.MONOTONIC, 0, &ts);
    return @as(f64, @floatFromInt(ts)) / 1e6;
}

pub export fn pw_now_ms() f64 {
    var ts: wasi.timestamp_t = 0;
    _ = wasi.clock_time_get(.REALTIME, 0, &ts);
    return @as(f64, @floatFromInt(ts)) / 1e6;
}
